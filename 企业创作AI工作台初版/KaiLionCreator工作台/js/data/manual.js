    nodes: NODE_STATS.total,
    visibleNodes: NODES.filter(n => n.visible).length,
    categories: NODE_STATS.categories,
    workflows: WORKFLOWS.length,
    workflowCats: WORKFLOW_CATS.length,
    libraries: libs.length,
    visibleLibs: libs.filter(l => l.factory).length,
